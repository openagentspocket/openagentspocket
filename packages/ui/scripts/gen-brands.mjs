// Generates src/theme/brands.generated.ts from tokens/brands.json (brand colors) and
// assets/program-logos/*.svg (Lobe Icons, MIT: see assets/program-logos/NOTICE-lobe-icons.txt).
//   node scripts/gen-brands.mjs           write the output
//   node scripts/gen-brands.mjs --check   fail if the committed output is stale
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(root, 'src/theme/brands.generated.ts');
const brands = JSON.parse(readFileSync(join(root, 'tokens/brands.json'), 'utf8'));

function fail(message) {
  console.error(`gen-brands: ${message}`);
  process.exit(1);
}

const attr = (tag, name) => tag.match(new RegExp(`\\s${name}="([^"]*)"`))?.[1];
const lines = [
  '// Generated by scripts/gen-brands.mjs from tokens/brands.json and assets/program-logos. Do not edit by hand.',
  '',
  'export interface LogoPath {',
  '  d: string;',
  '  opacity?: number;',
  '  clipRule?: boolean;',
  '}',
  '',
  'export const brandColors = {',
];
for (const [id, brand] of Object.entries(brands)) {
  if (!/^#[0-9A-F]{6}$/.test(brand.color)) fail(`${id}: ${brand.color} is not #RRGGBB`);
  lines.push(`  ${id}: '${brand.color}',`);
}
lines.push('} as const;', '', 'export const programLogos = {');
for (const [id, brand] of Object.entries(brands)) {
  const svg = readFileSync(join(root, `assets/program-logos/${brand.slug}.svg`), 'utf8');
  if (!svg.includes('viewBox="0 0 24 24"')) fail(`${id}: viewBox is not 24x24`);
  const paths = [...svg.matchAll(/<path\b[^>]*>/g)].map(([tag]) => {
    const d = attr(tag, 'd');
    if (!d) fail(`${id}: path without d`);
    const entry = [`d: '${d}'`];
    const opacity = attr(tag, 'opacity');
    if (opacity) entry.push(`opacity: ${Number(opacity)}`);
    if (attr(tag, 'clip-rule') === 'evenodd') entry.push('clipRule: true');
    return `{ ${entry.join(', ')} }`;
  });
  if (paths.length === 0) fail(`${id}: no paths`);
  lines.push(`  ${id}: [${paths.join(', ')}],`);
}
lines.push('} as const satisfies Record<keyof typeof brandColors, readonly LogoPath[]>;', '');
const output = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== output) fail('output is stale; run `pnpm -F @openagentspocket/ui gen`');
  console.log('gen-brands: up to date');
} else {
  writeFileSync(outputPath, output);
  console.log(`gen-brands: wrote ${Object.keys(brands).length} brands`);
}
