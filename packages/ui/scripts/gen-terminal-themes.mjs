// Generates src/theme/terminalThemes.generated.ts from tokens/terminal-themes/*.json (one file per theme).
//   node scripts/gen-terminal-themes.mjs           write the output
//   node scripts/gen-terminal-themes.mjs --check   fail if the committed output is stale
// Adding a terminal theme is one more JSON file there plus `pnpm gen`.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'tokens/terminal-themes');
const outputPath = join(root, 'src/theme/terminalThemes.generated.ts');

function fail(message) {
  console.error(`gen-terminal-themes: ${message}`);
  process.exit(1);
}

const hex = /^#[0-9a-fA-F]{6}$/;
function half(id, name, value) {
  if (!value) return undefined;
  const colors = [value.background, value.foreground, ...(value.ansi ?? [])];
  if (value.ansi?.length !== 16 || !colors.every((color) => hex.test(color))) {
    fail(`${id}.${name}: needs background, foreground and 16 ansi colors as #RRGGBB`);
  }
  return { background: value.background, foreground: value.foreground, ansi: value.ansi };
}

const themes = readdirSync(dir)
  .filter((file) => file.endsWith('.json'))
  .map((file) => {
    const doc = JSON.parse(readFileSync(join(dir, file), 'utf8'));
    if (`${doc.id}.json` !== file) fail(`${file}: id "${doc.id}" must match the file name`);
    if (typeof doc.order !== 'number' || !doc.title) fail(`${file}: needs order and title`);
    return {
      id: doc.id,
      order: doc.order,
      title: doc.title,
      detail: doc.detail ?? '',
      dark: half(doc.id, 'dark', doc.dark) ?? fail(`${file}: dark is required`),
      light: half(doc.id, 'light', doc.light),
    };
  })
  .sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));

const output = `// Generated by scripts/gen-terminal-themes.mjs from tokens/terminal-themes/*.json. Do not edit by hand.

export interface TerminalThemeColors {
  background: string;
  foreground: string;
  /** The 16 ANSI colors. */
  ansi: readonly string[];
}

export interface TerminalThemeData {
  id: string;
  order: number;
  title: string;
  /** The Swift description; the app translates it with the string as the catalog key. */
  detail: string;
  dark: TerminalThemeColors;
  /** Absent: the theme renders the same in Light Mode. */
  light?: TerminalThemeColors;
}

export const terminalThemes: readonly TerminalThemeData[] = ${JSON.stringify(themes, null, 2)};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== output) fail('output is stale; run `pnpm -F @openagentspocket/ui gen`');
  console.log('gen-terminal-themes: up to date');
} else {
  writeFileSync(outputPath, output);
  console.log(`gen-terminal-themes: wrote ${themes.length} themes`);
}
