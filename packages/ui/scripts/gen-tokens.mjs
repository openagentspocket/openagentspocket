// Generates src/theme/tokens.generated.ts from tokens/themes/*.json (one JSON per theme).
//   node scripts/gen-tokens.mjs           write the output
//   node scripts/gen-tokens.mjs --check   fail if the committed output is stale
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const themesDir = join(root, 'tokens/themes');
const outputPath = join(root, 'src/theme/tokens.generated.ts');
const HEX = /^#[0-9A-F]{6}$/;
const ORDER = ['indigo', 'papel', 'noche'];

function fail(message) {
  console.error(`gen-tokens: ${message}`);
  process.exit(1);
}

const themes = readdirSync(themesDir)
  .filter((file) => file.endsWith('.json'))
  .map((file) => JSON.parse(readFileSync(join(themesDir, file), 'utf8')))
  .sort((a, b) => ORDER.indexOf(a.id) - ORDER.indexOf(b.id));
if (themes.length === 0) fail('no themes found');

const keys = Object.keys(themes[0].colors);
for (const theme of themes) {
  if (!ORDER.includes(theme.id)) fail(`unknown theme id ${theme.id}`);
  if (!['dark', 'light'].includes(theme.appearance)) fail(`${theme.id}: bad appearance`);
  if (Object.keys(theme.colors).join() !== keys.join())
    fail(`${theme.id}: color keys differ from ${themes[0].id}`);
  for (const [key, value] of Object.entries(theme.colors)) {
    if (!HEX.test(value)) fail(`${theme.id}.${key}: ${value} is not #RRGGBB`);
  }
}

const lines = [
  '// Generated by scripts/gen-tokens.mjs from tokens/themes/*.json. Do not edit by hand.',
  '',
  `export const colorKeys = ${JSON.stringify(keys)} as const;`,
  'export type ColorKey = (typeof colorKeys)[number];',
  `export type ThemeId = ${ORDER.map((id) => `'${id}'`).join(' | ')};`,
  '',
  'export interface ThemeTokens {',
  '  id: ThemeId;',
  '  name: string;',
  "  appearance: 'dark' | 'light';",
  '  colors: Record<ColorKey, string>;',
  '}',
  '',
  `export const themeIds: readonly ThemeId[] = ${JSON.stringify(ORDER)};`,
  '',
  'export const themes: Record<ThemeId, ThemeTokens> = {',
];
for (const theme of themes) {
  lines.push(
    `  ${theme.id}: {`,
    `    id: '${theme.id}',`,
    `    name: ${JSON.stringify(theme.name)},`,
  );
  lines.push(`    appearance: '${theme.appearance}',`, '    colors: {');
  for (const key of keys) lines.push(`      ${key}: '${theme.colors[key]}',`);
  lines.push('    },', '  },');
}
lines.push('};', '');
const output = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== output) fail('output is stale; run `pnpm -F @agentico/ui gen`');
  console.log('gen-tokens: up to date');
} else {
  writeFileSync(outputPath, output);
  console.log(`gen-tokens: wrote ${themes.length} themes`);
}
