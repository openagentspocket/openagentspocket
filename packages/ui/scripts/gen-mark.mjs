// Generates src/brand/mark.generated.ts from tokens/mark.json: the app mark's geometry and its
// brand palette (the same file design/icon/gen_final.py draws the app icon from). The border's
// hue drift is precomputed here: the spectrum rotated to each hue the drift passes through.
//   node scripts/gen-mark.mjs           write the output
//   node scripts/gen-mark.mjs --check   fail if the committed output is stale
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(root, 'src/brand/mark.generated.ts');
const mark = JSON.parse(readFileSync(join(root, 'tokens/mark.json'), 'utf8'));
const HEX = /^#[0-9A-F]{6}$/;

function fail(message) {
  console.error(`gen-mark: ${message}`);
  process.exit(1);
}

function checkHex(where, value) {
  if (!HEX.test(value)) fail(`${where}: ${value} is not #RRGGBB`);
  return value;
}

/** CSS `hue-rotate(deg)` (Filter Effects spec matrix) applied to one sRGB color. */
function hueRotate(hex, deg) {
  const [r, g, b] = [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16));
  const a = (deg * Math.PI) / 180;
  const c = Math.cos(a);
  const s = Math.sin(a);
  const m = [
    [0.213 + c * 0.787 - s * 0.213, 0.715 - c * 0.715 - s * 0.715, 0.072 - c * 0.072 + s * 0.928],
    [0.213 - c * 0.213 + s * 0.143, 0.715 + c * 0.285 + s * 0.14, 0.072 - c * 0.072 - s * 0.283],
    [0.213 - c * 0.213 - s * 0.787, 0.715 - c * 0.715 + s * 0.715, 0.072 + c * 0.928 + s * 0.072],
  ];
  const channel = (row) =>
    Math.round(Math.min(255, Math.max(0, row[0] * r + row[1] * g + row[2] * b)));
  return `#${m.map((row) => channel(row).toString(16).padStart(2, '0')).join('')}`.toUpperCase();
}

const g = mark.geometry;
const [from, to] = mark.hueDrift;
const hues = [from, (from + to) / 2, to];
const stops = (list) =>
  `[${list.map((s) => `{ offset: ${s.offset}, color: '${s.color}' }`).join(', ')}]`;
const spectrum = mark.spectrum.map((s) => ({
  offset: s.offset,
  color: checkHex('spectrum', s.color),
}));
const pair = (name, [top, bottom]) =>
  `    ${name}: { top: '${checkHex(name, top)}', bottom: '${checkHex(name, bottom)}' },`;

const lines = [
  '// Generated by scripts/gen-mark.mjs from tokens/mark.json. Do not edit by hand.',
  '',
  '/** The mark in a 1024 x 1024 canvas (the app icon draws the same numbers). */',
  'export const markGeometry = {',
  `  canvas: ${g.canvas},`,
  `  card: { x: ${g.card.x}, y: ${g.card.y}, width: ${g.card.width}, height: ${g.card.height}, rx: ${g.card.rx} },`,
  `  pocket: '${g.pocket}',`,
  `  pivot: { x: ${g.pivot[0]}, y: ${g.pivot[1]} },`,
  `  cardCenter: { x: ${g.cardCenter[0]}, y: ${g.cardCenter[1]} },`,
  `  fanAngle: ${g.fanAngle},`,
  `  gap: ${g.gap},`,
  `  rimWidth: ${g.rimWidth},`,
  `  lift: ${g.lift},`,
  `  prompt: '${g.prompt}',`,
  `  promptWidth: ${g.promptWidth},`,
  '} as const;',
  '',
  '/** Brand colors of the mark (not theme colors): dark metal, a rim of light, the launch spectrum. */',
  'export const markPalette = {',
  `  background: '${checkHex('background', mark.background)}',`,
  '  metal: {',
  ...Object.entries(mark.metal).map(([name, colors]) => pair(name, colors)),
  '  },',
  `  rim: { color: '${checkHex('rim', mark.rim.color)}', stops: [${mark.rim.stops.map((s) => `{ offset: ${s.offset}, opacity: ${s.opacity} }`).join(', ')}] },`,
  `  spectrum: ${stops(spectrum)},`,
  `  /** The spectrum hue-rotated by ${hues.join(', ')} degrees: the border's drift, start to end. */`,
  '  spectrumDrift: [',
  ...hues.map(
    (deg) =>
      `    ${stops(spectrum.map((s) => ({ offset: s.offset, color: hueRotate(s.color, deg) })))},`,
  ),
  '  ],',
  '} as const;',
  '',
];
const output = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== output) fail('output is stale; run `pnpm -F @openagentspocket/ui gen`');
  console.log('gen-mark: up to date');
} else {
  writeFileSync(outputPath, output);
  console.log('gen-mark: wrote the mark');
}
