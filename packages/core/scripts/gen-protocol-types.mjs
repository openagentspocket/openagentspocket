// Generates src/protocol/herdr-types.generated.ts from schema/herdr-schema.json.
// herdr's $refs use a non-standard nested path (#/schemas/<schema>/$defs/X) and def names
// repeat across the five top-level schemas, so this flattens every $defs into one namespace
// (failing loudly if two same-named defs differ) before handing it to json-schema-to-typescript.
//
//   node scripts/gen-protocol-types.mjs           write the output
//   node scripts/gen-protocol-types.mjs --check   fail if the committed output is stale
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = join(root, 'schema/herdr-schema.json');
const outputPath = join(root, 'src/protocol/herdr-types.generated.ts');
const REF = /^#\/schemas\/[a-z_]+\/\$defs\/(\w+)$/;

function fail(message) {
  console.error(`gen-protocol-types: ${message}`);
  process.exit(1);
}

function rewriteRefs(node) {
  if (Array.isArray(node)) return node.map(rewriteRefs);
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === '$ref' && typeof value === 'string') {
      const match = REF.exec(value);
      if (!match) fail(`unrecognized $ref shape: ${value}`);
      out[key] = `#/$defs/${match[1]}`;
    } else {
      out[key] = rewriteRefs(value);
    }
  }
  return out;
}

const source = JSON.parse(readFileSync(schemaPath, 'utf8'));
const defs = {};
const origin = {};
const roots = {};
for (const name of Object.keys(source.schemas).sort()) {
  const { $defs = {}, $schema: _schema, ...rest } = source.schemas[name];
  for (const [defName, definition] of Object.entries($defs)) {
    const rewritten = rewriteRefs(definition);
    if (defName in defs && JSON.stringify(defs[defName]) !== JSON.stringify(rewritten)) {
      fail(`$defs/${defName} differs between '${origin[defName]}' and '${name}'`);
    }
    defs[defName] = rewritten;
    origin[defName] ??= name;
  }
  const rootName = rest.title;
  if (rootName in defs) fail(`root schema title ${rootName} collides with a $defs entry`);
  roots[rootName] = rewriteRefs(rest);
}

const combined = {
  title: 'HerdrProtocol',
  type: 'object',
  additionalProperties: false,
  properties: Object.fromEntries(
    Object.keys(roots).map((name) => [name, { $ref: `#/$defs/${name}` }]),
  ),
  $defs: { ...defs, ...roots },
};

const banner = `/* eslint-disable */
// Generated by scripts/gen-protocol-types.mjs from schema/herdr-schema.json
// (herdr protocol ${source.protocol}, schema_version ${source.schema_version}). Do not edit by hand.
`;
const body = await compile(combined, 'HerdrProtocol', {
  bannerComment: banner,
  additionalProperties: false,
  style: { singleQuote: true },
  format: false,
  unreachableDefinitions: true,
});
const output = body.replace(/[ \t]+$/gm, '');

if (process.argv.includes('--check')) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== output) fail('output is stale; run `pnpm -F @agentico/core gen`');
  console.log('gen-protocol-types: up to date');
} else {
  writeFileSync(outputPath, output);
  console.log(`gen-protocol-types: wrote ${outputPath} (${output.split('\n').length} lines)`);
}
