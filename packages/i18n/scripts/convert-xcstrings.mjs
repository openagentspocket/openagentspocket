// Converts the Swift app's String Catalogs into src/catalogs/<locale>/<table>.json (ICU) and
// writes src/catalogs.generated.ts, the static registry Metro bundles.
//   node scripts/convert-xcstrings.mjs [--swift <dir>]           write the output
//   node scripts/convert-xcstrings.mjs [--swift <dir>] --check   fail if the committed output is stale
// The Swift checkout defaults to $AGENTICO_SWIFT_DIR, else a sibling `Agentico` folder of this repo.
// Never edit the JSON by hand: fix the wording in the Swift catalog and convert again.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { convertSwiftCatalogs, LOCALES } from './xcstrings.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const flag = args.indexOf('--swift');
const swiftDir = resolve(
  flag >= 0 ? args[flag + 1] : (process.env.AGENTICO_SWIFT_DIR ?? join(root, '../../../Agentico')),
);
const check = args.includes('--check');

function fail(message) {
  console.error(`ERROR convert-xcstrings: ${message}`);
  process.exit(1);
}

if (!existsSync(join(swiftDir, 'Sources')))
  fail(`no Swift checkout at ${swiftDir}; pass --swift <dir> or set AGENTICO_SWIFT_DIR`);

let tables;
try {
  tables = convertSwiftCatalogs(swiftDir);
} catch (error) {
  fail(error.message);
}

const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const ident = (table, locale) => `${table}${locale.charAt(0).toUpperCase()}${locale.slice(1)}`;
const outputs = new Map();
for (const { table, en, es } of tables) {
  const byLocale = { en, es };
  for (const locale of LOCALES)
    outputs.set(`src/catalogs/${locale}/${table}.json`, json(byLocale[locale]));
}
const registry = [
  '// Generated by scripts/convert-xcstrings.mjs from the Swift String Catalogs. Do not edit.',
  ...tables.flatMap(({ table }) =>
    LOCALES.map(
      (locale) => `import ${ident(table, locale)} from './catalogs/${locale}/${table}.json';`,
    ),
  ),
  '',
  '/** Where each table comes from, relative to the Swift checkout. */',
  'export const catalogSources = {',
  ...tables.map(({ table, path }) => `  ${table}: '${path}',`),
  '} as const;',
  '',
  '/** Every table per locale: `catalogs[locale][table][key]` is an ICU message. */',
  'export const catalogs = {',
  ...LOCALES.flatMap((locale) => [
    `  ${locale}: {`,
    ...tables.map(({ table }) => `    ${table}: ${ident(table, locale)},`),
    '  },',
  ]),
  '} as const;',
  '',
].join('\n');
outputs.set('src/catalogs.generated.ts', registry);

const stale = [];
for (const [path, content] of outputs) {
  const full = join(root, path);
  const current = existsSync(full) ? readFileSync(full, 'utf8') : undefined;
  if (current === content) continue;
  if (check) {
    stale.push(path);
    continue;
  }
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content);
}
if (check && stale.length) fail(`stale, run the converter: ${stale.join(', ')}`);

const keys = tables.reduce((sum, { en }) => sum + Object.keys(en).length, 0);
const skipped = tables.reduce((sum, { skipped: list }) => sum + list.length, 0);
console.log(
  `convert-xcstrings: ${tables.length} tables, ${keys} keys, ${skipped} stale skipped${check ? ', up to date' : ''}`,
);
