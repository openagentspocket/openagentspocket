#!/usr/bin/env node
// Renders docs/PROGRESS.md (what is done, what is left) from the backlog in
// docs/tasks.yml and the worker reports in docs/progress/<task-id>.md. A
// task's status is its merged report's `status:` line; without a report it is
// "ready" when every dependency is done (or partial, its leftovers filed as
// tasks), else "waiting". Nothing is edited by
// hand: run `pnpm progress` after each merge. `--check` fails when the file
// is stale.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from 'yaml';

const root = join(import.meta.dirname, '..');
const tasks = parse(readFileSync(join(root, 'docs/tasks.yml'), 'utf8'));
const out = join(root, 'docs/PROGRESS.md');

const reported = new Map();
for (const task of tasks) {
  const file = join(root, 'docs/progress', `${task.id}.md`);
  if (!existsSync(file)) continue;
  const match = readFileSync(file, 'utf8').match(/^status:\s*(\w+)/m);
  reported.set(task.id, match ? match[1] : 'done');
}

const statusOf = (task) =>
  reported.get(task.id) ??
  // A partial dependency counts: its leftovers are filed as their own tasks.
  ((task.deps ?? []).every((dep) => ['done', 'partial'].includes(reported.get(dep)))
    ? 'ready'
    : 'waiting');

const phases = [...new Set(tasks.map((task) => task.phase))].sort((a, b) => a - b);
const count = (list, status) => list.filter((task) => statusOf(task) === status).length;

const lines = [
  '# Progress',
  '',
  'Generated by `pnpm progress` from `docs/tasks.yml` and `docs/progress/*.md`. Do not edit.',
  '',
  `**${count(tasks, 'done')} of ${tasks.length} tasks done.** Ready now: ${count(tasks, 'ready')}, partial: ${count(tasks, 'partial')}, blocked: ${count(tasks, 'blocked')}.`,
  '',
  '| Phase | Done | Partial | Ready | Waiting | Blocked |',
  '|---|---|---|---|---|---|',
];
for (const phase of phases) {
  const list = tasks.filter((task) => task.phase === phase);
  lines.push(
    `| ${phase} | ${count(list, 'done')}/${list.length} | ${count(list, 'partial')} | ${count(list, 'ready')} | ${count(list, 'waiting')} | ${count(list, 'blocked')} |`,
  );
}
for (const phase of phases) {
  lines.push('', `## Phase ${phase}`, '', '| Task | Kind | Status | Report |', '|---|---|---|---|');
  for (const task of tasks.filter((entry) => entry.phase === phase)) {
    const report = reported.has(task.id) ? `[report](progress/${task.id}.md)` : '';
    lines.push(`| ${task.id}: ${task.title} | ${task.kind} | ${statusOf(task)} | ${report} |`);
  }
}
const text = `${lines.join('\n')}\n`;

if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== text) {
    console.error('ERROR docs/PROGRESS.md is stale: run pnpm progress');
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
  console.log(`docs/PROGRESS.md: ${count(tasks, 'done')}/${tasks.length} done`);
}
