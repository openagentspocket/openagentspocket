// Regenerates apps/mobile/src/settings/notices.generated.ts from the Swift app's Notices folder.
//   node scripts/gen-notices.mjs --swift <path to the Swift checkout>   (or AGENTICO_SWIFT_DIR)
// Only the components this app bundles (themes, icons, fonts, SSH) are kept.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const flag = process.argv.indexOf('--swift');
const swift = resolve(
  flag > 0 ? process.argv[flag + 1] : (process.env.AGENTICO_SWIFT_DIR ?? join(ROOT, '../Agentico')),
);
const notices = join(swift, 'Sources/Agentico/Resources/Notices');
const OUT = join(ROOT, 'apps/mobile/src/settings/notices.generated.ts');

const KEEP = [
  'Catppuccin',
  'Gruvbox',
  'IBMPlexMono',
  'JetBrainsMono',
  'LobeIcons',
  'Lucide',
  'Nord',
  'OpenSSL',
  'libssh2',
  'libssh2-bcrypt_pbkdf',
  'libssh2-cipher-chachapoly',
];
// Sources that name a path inside the Swift repo get their public home instead.
const SOURCES = {
  IBMPlexMono: 'https://github.com/IBM/plex',
  OpenSSL: 'https://www.openssl.org',
  libssh2: 'https://github.com/libssh2/libssh2',
  'libssh2-bcrypt_pbkdf': 'https://github.com/libssh2/libssh2',
  'libssh2-cipher-chachapoly': 'https://github.com/libssh2/libssh2',
};

const inventory = JSON.parse(readFileSync(join(notices, 'inventory.json'), 'utf8'));
const rows = inventory.components
  .filter((c) => KEEP.includes(c.id))
  .sort((a, b) => a.displayName.localeCompare(b.displayName))
  .map((c) => ({
    id: c.id,
    name: c.displayName,
    version: c.version ?? '',
    spdx: c.spdx,
    source: SOURCES[c.id] ?? c.source.split(' (')[0],
    text: readFileSync(join(notices, c.notice), 'utf8').trim(),
  }));

const body = rows.map((row) => `  ${JSON.stringify(row)},`).join('\n');
writeFileSync(
  OUT,
  `// Generated by scripts/gen-notices.mjs from the Swift app's Notices/inventory.json. Do not edit by hand.

export interface Notice {
  id: string;
  name: string;
  version: string;
  spdx: string;
  source: string;
  text: string;
}

export const NOTICES: readonly Notice[] = [
${body}
];
`,
);
console.log(`wrote ${rows.length} notices`);
