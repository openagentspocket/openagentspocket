#!/usr/bin/env node
// Renders docs/ux/components/README.md from docs/ux/components/catalog.json and checks the catalog:
// unique names, every crop key belongs to a catalog component/variant, every ref image exists,
// every group has its UX3 task in docs/tasks.yml, Swift sources exist (when the Swift repo is
// reachable). `--check` fails when README.md is stale or a rule breaks; without it README is rewritten.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from 'yaml';

const root = join(import.meta.dirname, '..');
const dir = join(root, 'docs/ux/components');
const catalog = JSON.parse(readFileSync(join(dir, 'catalog.json'), 'utf8'));
const crops = JSON.parse(readFileSync(join(dir, 'crops.json'), 'utf8')).crops;
const tasks = parse(readFileSync(join(root, 'docs/tasks.yml'), 'utf8'));
const swiftRepo = [join(root, '../Agentico'), join(root, '../../../../Agentico')].find((d) =>
  existsSync(join(d, 'docs/ux/screens.yml')),
);

const errors = [];
const names = new Set();
const keys = new Set();
for (const c of catalog.components) {
  if (names.has(c.name)) errors.push(`duplicate component ${c.name}`);
  names.add(c.name);
  if (!catalog.groups[c.group]) errors.push(`${c.name}: unknown group ${c.group}`);
  for (const v of c.variants) {
    const id = v.split('|')[0];
    keys.add(id === 'default' ? c.name : `${c.name}.${id}`);
  }
  if (swiftRepo)
    for (const s of c.swift) {
      const file = s.split(':')[0];
      if (!existsSync(join(swiftRepo, 'Sources/Agentico', file)))
        errors.push(`${c.name}: missing Swift file ${file}`);
    }
}
for (const [group, info] of Object.entries(catalog.groups))
  if (!tasks.some((t) => t.id === info.task))
    errors.push(`group ${group}: task ${info.task} not in docs/tasks.yml`);
for (const key of Object.keys(crops)) {
  if (!keys.has(key)) errors.push(`crops.json: ${key} is not a catalog variant`);
  if (!existsSync(join(dir, 'ref', `${key}.png`)))
    errors.push(`missing ref/${key}.png (run scripts/ux-crop.py)`);
  if (crops[key].light && !existsSync(join(dir, 'ref', `${key}.light.png`)))
    errors.push(`missing ref/${key}.light.png`);
}

const cropOf = (key) =>
  crops[key]
    ? `[ref](ref/${key}.png)${crops[key].light ? ` · [light](ref/${key}.light.png)` : ''}`
    : 'none';
const link = (file) => (file.includes(' ') || file === 'none' ? file : `\`${file}\``);
const lines = [];
lines.push(
  '<!-- Generated by scripts/ux-catalog.mjs from catalog.json. Edit catalog.json, not this file. -->',
);
lines.push('# Component catalog (UX2)');
lines.push('');
lines.push(
  'The UX program goes component first: each Swift visual component is cloned once into `packages/ui/src/components/<Name>.tsx`,',
  'reused by every screen, and judged against a crop of the Swift atlas. Whole screens are assembled afterwards (the `UX1-*` tasks).',
  'Skin: Índigo default, Papel light, Noche optional; cards radius 8 with a hairline; airy density (x1.3 of the Swift spacing). The atlas',
  'is the old Noche skin: copy structure, spacing and behavior, never colors.',
  '',
  '## Loop for a UX3 worker',
  '',
  '1. Read your group below, the Swift files (line ranges), the crops in `ref/` (open the PNGs) and [../design-system.md](../design-system.md).',
  '2. Implement each component in `packages/ui/src/components/<Name>.tsx` (<= 400 lines, colors from tokens, strings through `t()`), compose primitives, add a props type and export it from your group barrel `packages/ui/src/components/<gallery file name>.ts` (already re-exported by `packages/ui/src/index.ts`; do not edit index.ts).',
  '3. Register demos in `packages/ui/src/gallery/components/<group>.tsx` (the file your task owns): one `CatalogEntry` per component, one variant per row of its variants list, ids equal to the variant ids, demo props only (no app state).',
  '4. Capture and compare: `node scripts/ux-components.mjs --port 8123 [Name ...]` then `V/bin/python3 scripts/atlas-compare.py --components` writes `design/atlas/components/compare/<Name>[.<variant>].png` (Swift crop | RN Índigo | RN Papel). Iterate until the checklist holds.',
  '5. Component tests pin behavior (press, menu, states) with jest-expo; `pnpm verify-fast`; `docs/progress/<task>.md`; `pnpm progress`.',
  '',
  'A component is done when its gallery entry renders every variant in Índigo and Papel, the checklist below holds on the side-by-side sheet, and no screen',
  'outside `packages/ui/src/components` was needed. Screens then swap their local markup for the component in the matching `UX1-*` assembly task.',
  '',
  '## Groups (tasks)',
  '',
  '| Task | Gallery file | Components |',
  '|---|---|---|',
);
for (const [group, info] of Object.entries(catalog.groups)) {
  const list = catalog.components.filter((c) => c.group === group).map((c) => c.name);
  lines.push(`| ${info.task} | \`gallery/components/${info.gallery}.tsx\` | ${list.join(', ')} |`);
}
lines.push(
  '',
  '## Catalog',
  '',
  '| Component | Task | Atlas screens | Crops | RN today | Swift |',
  '|---|---|---|---|---|---|',
);
for (const c of catalog.components) {
  const crop = c.variants
    .map((v) => v.split('|')[0])
    .map((id) => `${id}: ${cropOf(id === 'default' ? c.name : `${c.name}.${id}`)}`)
    .join('<br>');
  lines.push(
    `| [${c.name}](#${c.name.toLowerCase()}) | ${catalog.groups[c.group].task} | ${c.screens.map((s) => `\`${s}\``).join('<br>')} | ${crop} | ${c.rnToday.map(link).join('<br>')} | ${c.swift.map((s) => `\`${s}\``).join('<br>')} |`,
  );
}
for (const c of catalog.components) {
  lines.push('', `## ${c.name}`, '');
  lines.push(
    `Task ${catalog.groups[c.group].task} · target \`packages/ui/src/components/${c.name}.tsx\` · composes ${c.composes.join(', ')}`,
    '',
  );
  lines.push(`Props sketch: \`${c.props}\``, '');
  lines.push(
    `Interactions: ${c.interactions}`,
    '',
    'Variants (gallery variant id = the id before the colon):',
    '',
  );
  for (const v of c.variants) {
    const [id, note] = v.split('|');
    const key = id === 'default' ? c.name : `${c.name}.${id}`;
    lines.push(`- \`${id}\`: ${note} · crop ${cropOf(key)}`);
  }
  lines.push('', 'Acceptance (the judge ticks each on the side-by-side):', '');
  for (const a of c.accept) lines.push(`- [ ] ${a}`);
}
const readme = `${lines.join('\n')}\n`;
const target = join(dir, 'README.md');
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== readme)
    errors.push('docs/ux/components/README.md is stale: run node scripts/ux-catalog.mjs');
  if (errors.length) {
    for (const e of errors) console.error(`ERROR ${e}`);
    process.exit(1);
  }
  console.log(
    `ux catalog ok (${catalog.components.length} components, ${Object.keys(crops).length} crops)`,
  );
} else {
  if (errors.length) for (const e of errors) console.error(`ERROR ${e}`);
  writeFileSync(target, readme);
  console.log(`wrote ${target}`);
}
